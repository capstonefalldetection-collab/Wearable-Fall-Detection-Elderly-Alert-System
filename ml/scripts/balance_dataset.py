"""
Balance the SisFall windows generated by prepare_sisfall.py.

Class balancing: long ADL recordings produce many sliding-window no_fall samples,
while each fall file contributes ~1 fall window (33:1 before balancing).

Method: stratified downsampling of no_fall windows by (subject, activity_code),
so we don't just keep whichever activity happened to be longest -- we keep
proportional variety across all subjects and all ~19 ADL types. Optionally
also augment the fall class to push the effective ratio down further
without throwing away real diversity.
"""

import re
import random
import shutil
import numpy as np
import pandas as pd
from pathlib import Path
from collections import defaultdict

WINDOWS_DIR = Path("SisFall_windows")
FALL_DIR = WINDOWS_DIR / "fall"
NOFALL_DIR = WINDOWS_DIR / "no_fall"
BALANCED_DIR = WINDOWS_DIR / "balanced"

TARGET_RATIO = 3.0          # aim for no_fall:fall ~= 3:1 after downsampling
FALL_AUGMENT_MULTIPLIER = 2  # also 2x the fall class via light augmentation
RNG_SEED = 42

# no_fall filenames look like: no_fall_SA01_D01_R01_00001.csv
FNAME_META_RE = re.compile(r"^no_fall_([A-Z]{2}\d+)_([A-Z]\d+)_R\d+_\d+\.csv$")


def stratified_sample_nofall():
    groups = defaultdict(list)
    for f in NOFALL_DIR.glob("*.csv"):
        m = FNAME_META_RE.match(f.name)
        if not m:
            continue
        subject, activity = m.groups()
        groups[(subject, activity)].append(f)

    n_fall = len(list(FALL_DIR.glob("*.csv")))
    target_total = int(n_fall * TARGET_RATIO)

    rng = random.Random(RNG_SEED)
    per_group_target = max(1, target_total // len(groups))

    selected = []
    for key, files in groups.items():
        rng.shuffle(files)
        selected.extend(files[:per_group_target])

    # Trim/pad to hit target_total exactly, staying random.
    rng.shuffle(selected)
    selected = selected[:target_total]

    print(f"no_fall groups (subject, activity): {len(groups)}")
    print(f"selected {len(selected)} of available no_fall windows "
          f"(target was {target_total}) against {n_fall} fall windows")
    return selected


def augment_window(df: pd.DataFrame) -> pd.DataFrame:
    """Light augmentation: small sensor noise + small rotation-like jitter."""
    out = df.copy()
    accel_cols = [c for c in df.columns if c.startswith(("acc1_", "acc2_"))]
    gyro_cols = [c for c in df.columns if c.startswith("gyro_")]

    noise_g = np.random.normal(0, 0.03, size=len(df))       # ~0.03g jitter
    noise_dps = np.random.normal(0, 1.0, size=len(df))       # ~1 deg/s jitter
    for c in accel_cols:
        out[c] = out[c] + noise_g
    for c in gyro_cols:
        out[c] = out[c] + noise_dps

    # Re-derive svm if present
    if "svm_g" in out.columns:
        out["svm_g"] = np.sqrt(out.acc1_x**2 + out.acc1_y**2 + out.acc1_z**2)
    return out


def main():
    random.seed(RNG_SEED)
    np.random.seed(RNG_SEED)

    (BALANCED_DIR / "fall").mkdir(parents=True, exist_ok=True)
    (BALANCED_DIR / "no_fall").mkdir(parents=True, exist_ok=True)

    # 1. Copy all fall windows as-is, plus augmented copies.
    fall_files = list(FALL_DIR.glob("*.csv"))
    for f in fall_files:
        shutil.copy(f, BALANCED_DIR / "fall" / f.name)

    for f in fall_files:
        df = pd.read_csv(f)
        for i in range(FALL_AUGMENT_MULTIPLIER - 1):
            aug = augment_window(df)
            aug_name = f.stem + f"_aug{i+1}.csv"
            aug.to_csv(BALANCED_DIR / "fall" / aug_name, index=False)

    # 2. Stratified-sample no_fall and copy.
    selected_nofall = stratified_sample_nofall()
    for f in selected_nofall:
        shutil.copy(f, BALANCED_DIR / "no_fall" / f.name)

    n_fall_final = len(list((BALANCED_DIR / "fall").glob("*.csv")))
    n_nofall_final = len(list((BALANCED_DIR / "no_fall").glob("*.csv")))
    print(f"\nFinal balanced set -> fall: {n_fall_final}, no_fall: {n_nofall_final}, "
          f"ratio: {n_nofall_final / n_fall_final:.2f}")
    print(f"Output written to: {BALANCED_DIR}")


if __name__ == "__main__":
    main()
